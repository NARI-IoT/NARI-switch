function renderVectorText(text, startX, startY, heightMm = 1.6) {
  const scale = heightMm / 6.0;
  const charWidth = 4.0 * scale;
  const charSpacing = 1.5 * scale;
  const strokes = [];

  let curX = startX;
  const upper = text.toUpperCase();
  for (let i = 0; i < upper.length; i++) {
    const ch = upper[i];
    const glyph = FONT[ch] || FONT['-'];
    for (const seg of glyph) {
      strokes.push({
        x1: curX + seg[0][0] * scale,
        y1: startY + seg[0][1] * scale,
        x2: curX + seg[1][0] * scale,
        y2: startY + seg[1][1] * scale
      });
    }
    curX += charWidth + charSpacing;
  }
  return strokes;
}

